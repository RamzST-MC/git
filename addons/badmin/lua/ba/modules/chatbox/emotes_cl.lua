local function loadEmotesList(data)
	for _, emojiSet in pairs(data) do
		for k, v in pairs(emojiSet.Emotes) do
			local em = ':' .. k .. ':'
			ba.chatEmotes[em] = {
			name = em,
				loadUrl = string.Replace(emojiSet.ImageUrl, '{item_id}', tostring(v)),
				mat = false
			}
		end
	end
end

